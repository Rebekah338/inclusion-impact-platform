'use client';

import { useState, useEffect, useRef } from 'react';
import PlatformNav from '@/app/components/PlatformNav';
import BottomBanner from '@/app/components/BottomBanner';

const SECTORS = [
  'Private sector','Public sector','Third sector / Charity',
  'Education (schools)','Education (higher education)','Healthcare / NHS',
  'Financial services','Legal','Technology','Hospitality and retail','Other',
];
const TONES = ['Formal','Balanced','Direct and transparent'];
const LOADING_STEPS = [
  'Reading your figures...','Benchmarking against your sector...',
  'Drafting your narrative statement...','Reviewing your actions...',
  'Generating your next steps...','Finalising your output...',
];

interface Result {
  orgName: string; sector: string; reportingYear: string;
  meanPayGap: string; medianPayGap: string;
  meanComparison: string; medianComparison: string;
  benchMean: number; benchMedian: number;
  statement: string; sectorContext: string;
  actionsReview: string; strengthenNext: string; shortVersion: string;
}

function buildFullText(r: Result): string {
  const lines: string[] = [];
  lines.push(r.orgName ? `GENDER PAY GAP STATEMENT: ${r.orgName.toUpperCase()}` : 'GENDER PAY GAP STATEMENT');
  if (r.reportingYear) lines.push(`Reporting year: ${r.reportingYear}`);
  lines.push('Generated by The Inclusion Edit\n');
  lines.push('---\n\nOUR STATEMENT\n');
  lines.push(r.statement);
  lines.push('\n---\n\nSECTOR CONTEXT\n');
  lines.push(r.sectorContext);
  lines.push('\n---\n\nACTIONS REVIEW\n');
  lines.push(r.actionsReview);
  lines.push('\n---\n\nSTRENGTHEN NEXT YEAR\n');
  lines.push(r.strengthenNext);
  lines.push('\n---\n\nSHORT VERSION (for social or internal use)\n');
  lines.push(r.shortVersion);
  return lines.join('\n');
}

export default function GenderPayGapStatementBuilderPage() {
  const [orgName, setOrgName] = useState('');
  const [sector, setSector] = useState('');
  const [reportingYear, setReportingYear] = useState('');
  const [tone, setTone] = useState('Balanced');
  const [meanPayGap, setMeanPayGap] = useState('');
  const [medianPayGap, setMedianPayGap] = useState('');
  const [meanBonusGap, setMeanBonusGap] = useState('');
  const [medianBonusGap, setMedianBonusGap] = useState('');
  const [menBonus, setMenBonus] = useState('');
  const [womenBonus, setWomenBonus] = useState('');
  const [quartileMale, setQuartileMale] = useState({ upper:'', upperMiddle:'', lowerMiddle:'', lower:'' });
  const [quartileFemale, setQuartileFemale] = useState({ upper:'', upperMiddle:'', lowerMiddle:'', lower:'' });
  const [mainDriver, setMainDriver] = useState('');
  const [actions, setActions] = useState('');
  const [loading, setLoading] = useState(false);
  const [loadingStep, setLoadingStep] = useState(0);
  const [result, setResult] = useState<Result|null>(null);
  const [error, setError] = useState('');
  const [copied, setCopied] = useState<string|null>(null);
  const stepRef = useRef<NodeJS.Timeout|null>(null);

  useEffect(() => {
    if (loading) { stepRef.current = setInterval(() => setLoadingStep(s => (s+1)%LOADING_STEPS.length), 1800); }
    else { if (stepRef.current) clearInterval(stepRef.current); setLoadingStep(0); }
    return () => { if (stepRef.current) clearInterval(stepRef.current); };
  }, [loading]);

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    if (!sector || !meanPayGap || !medianPayGap || !mainDriver || !actions) return;
    setLoading(true); setError(''); setResult(null);
    try {
      const res = await fetch('/api/gender-pay-gap-statement-builder', {
        method:'POST', headers:{'Content-Type':'application/json'},
        body: JSON.stringify({ orgName, sector, reportingYear, tone, meanPayGap, medianPayGap, meanBonusGap, medianBonusGap, menBonus, womenBonus, quartileMale, quartileFemale, mainDriver, actions }),
      });
      const json = await res.json();
      if (!res.ok) throw new Error(json.error || 'Something went wrong');
      setResult(json);
    } catch(err) { setError(err instanceof Error ? err.message : 'Something went wrong'); }
    finally { setLoading(false); }
  }

  function copy(text: string, key: string) {
    navigator.clipboard.writeText(text).then(() => { setCopied(key); setTimeout(() => setCopied(null), 2000); });
  }

  const inp: React.CSSProperties = { width:'100%', padding:'11px 13px', border:'1px solid var(--gray-soft)', borderRadius:8, fontSize:15, background:'var(--white)', color:'var(--charcoal)', boxSizing:'border-box', outline:'none', fontFamily:'inherit' };
  const lbl: React.CSSProperties = { display:'block', fontSize:14, fontWeight:600, color:'var(--charcoal)', marginBottom:4 };
  const hint: React.CSSProperties = { fontSize:13, color:'#888', margin:'0 0 7px 0', lineHeight:1.5 };
  const card: React.CSSProperties = { background:'var(--white)', borderRadius:12, padding:'24px 28px', boxShadow:'0 1px 4px rgba(0,0,0,0.06)', marginBottom:16 };
  const sectionH: React.CSSProperties = { fontSize:16, fontWeight:700, color:'var(--charcoal)', margin:'0 0 18px 0' };

  const QUARTILE_ROWS = [
    { key:'upper', label:'Upper quartile (highest paid)' },
    { key:'upperMiddle', label:'Upper middle quartile' },
    { key:'lowerMiddle', label:'Lower middle quartile' },
    { key:'lower', label:'Lower quartile (lowest paid)' },
  ];

  return (
    <div style={{ minHeight:'100vh', background:'var(--sage-xlight)', display:'flex', flexDirection:'column' }}>
      <PlatformNav />
      <main style={{ flex:1, padding:'40px 24px', maxWidth:900, margin:'0 auto', width:'100%', boxSizing:'border-box' }}>

        {!result && !loading && (
          <>
            <div style={{ marginBottom:32 }}>
              <div style={{ display:'inline-block', background:'var(--charcoal)', color:'var(--white)', fontSize:11, fontWeight:700, letterSpacing:'0.08em', textTransform:'uppercase', padding:'4px 10px', borderRadius:4, marginBottom:12 }}>AI Inclusion Tool</div>
              <h1 style={{ fontSize:28, fontWeight:700, color:'var(--charcoal)', margin:'0 0 12px 0' }}>Gender Pay Gap Statement Builder</h1>
              <p style={{ fontSize:16, color:'#444', lineHeight:1.7, maxWidth:680, margin:'0 0 10px 0' }}>
                Every UK employer with 250 or more employees is required by law to publish six gender pay gap figures each year. The numbers go on the government&apos;s reporting portal by 4 April. The written explanation does not. But it should.
              </p>
              <p style={{ fontSize:16, color:'#444', lineHeight:1.7, maxWidth:680, margin:'0 0 10px 0' }}>
                A narrative statement transforms a set of statistics into something people can actually understand: what the gap reflects, why it exists, and what your organisation is doing about it. Without it, the numbers sit on a government database and do very little.
              </p>
              <p style={{ fontSize:16, color:'#444', lineHeight:1.7, maxWidth:680, margin:'0 0 16px 0' }}>
                This tool takes your published figures and generates a clear, honest narrative you can publish on your website, include in your annual report, or share with employees. No personal data required: just the aggregated figures you already have.
              </p>
              <p style={{ fontSize:14, color:'#888' }}>Takes around 5 minutes to complete.</p>
            </div>

            <form onSubmit={handleSubmit}>
              <div style={card}>
                <h2 style={sectionH}>About your organisation</h2>
                <div style={{ display:'grid', gridTemplateColumns:'1fr 1fr', gap:16, marginBottom:16 }}>
                  <div>
                    <label style={lbl}>Organisation name <span style={{ color:'#aaa', fontWeight:400 }}>(optional)</span></label>
                    <input type="text" value={orgName} onChange={e => setOrgName(e.target.value)} placeholder="e.g. Northfield Group" style={inp} />
                  </div>
                  <div>
                    <label style={lbl}>Reporting year <span style={{ color:'#aaa', fontWeight:400 }}>(optional)</span></label>
                    <input type="text" value={reportingYear} onChange={e => setReportingYear(e.target.value)} placeholder="e.g. 2024/25" style={inp} />
                  </div>
                </div>
                <div style={{ display:'grid', gridTemplateColumns:'1fr 1fr', gap:16, marginBottom:16 }}>
                  <div>
                    <label style={lbl}>Sector <span style={{ color:'#c00' }}>*</span></label>
                    <select value={sector} onChange={e => setSector(e.target.value)} style={{ ...inp, cursor:'pointer' }} required>
                      <option value="">Select sector</option>
                      {SECTORS.map(s => <option key={s} value={s}>{s}</option>)}
                    </select>
                  </div>
                  <div>
                    <label style={lbl}>Statement tone</label>
                    <p style={hint}>How do you want the statement to read?</p>
                    <select value={tone} onChange={e => setTone(e.target.value)} style={{ ...inp, cursor:'pointer' }}>
                      {TONES.map(t => <option key={t} value={t}>{t}</option>)}
                    </select>
                  </div>
                </div>
              </div>

              <div style={card}>
                <h2 style={sectionH}>Your pay gap figures</h2>
                <p style={{ fontSize:14, color:'#777', margin:'0 0 18px 0' }}>Enter your statutory figures as percentages (e.g. 14.2). A positive figure means men earn more on average.</p>
                <div style={{ display:'grid', gridTemplateColumns:'1fr 1fr', gap:16, marginBottom:16 }}>
                  <div>
                    <label style={lbl}>Mean gender pay gap % <span style={{ color:'#c00' }}>*</span></label>
                    <p style={hint}>The difference in average hourly pay between men and women</p>
                    <input type="number" step="0.1" value={meanPayGap} onChange={e => setMeanPayGap(e.target.value)} placeholder="e.g. 18.4" style={inp} required />
                  </div>
                  <div>
                    <label style={lbl}>Median gender pay gap % <span style={{ color:'#c00' }}>*</span></label>
                    <p style={hint}>The midpoint figure; less affected by very high or very low earners</p>
                    <input type="number" step="0.1" value={medianPayGap} onChange={e => setMedianPayGap(e.target.value)} placeholder="e.g. 14.1" style={inp} required />
                  </div>
                  <div>
                    <label style={lbl}>Mean bonus gap % <span style={{ color:'#aaa', fontWeight:400 }}>(optional)</span></label>
                    <input type="number" step="0.1" value={meanBonusGap} onChange={e => setMeanBonusGap(e.target.value)} placeholder="e.g. 32.0" style={inp} />
                  </div>
                  <div>
                    <label style={lbl}>Median bonus gap % <span style={{ color:'#aaa', fontWeight:400 }}>(optional)</span></label>
                    <input type="number" step="0.1" value={medianBonusGap} onChange={e => setMedianBonusGap(e.target.value)} placeholder="e.g. 24.5" style={inp} />
                  </div>
                  <div>
                    <label style={lbl}>Men receiving a bonus % <span style={{ color:'#aaa', fontWeight:400 }}>(optional)</span></label>
                    <input type="number" step="0.1" value={menBonus} onChange={e => setMenBonus(e.target.value)} placeholder="e.g. 68" style={inp} />
                  </div>
                  <div>
                    <label style={lbl}>Women receiving a bonus % <span style={{ color:'#aaa', fontWeight:400 }}>(optional)</span></label>
                    <input type="number" step="0.1" value={womenBonus} onChange={e => setWomenBonus(e.target.value)} placeholder="e.g. 54" style={inp} />
                  </div>
                </div>
              </div>

              <div style={card}>
                <h2 style={sectionH}>Pay quartile breakdown</h2>
                <p style={{ fontSize:14, color:'#777', margin:'0 0 18px 0' }}>Enter the percentage of men and women in each pay band, from highest to lowest paid.</p>
                <div style={{ display:'grid', gridTemplateColumns:'2fr 1fr 1fr', gap:'8px 16px', alignItems:'center' }}>
                  <div style={{ fontSize:13, fontWeight:700, color:'#888', paddingBottom:4 }}>Quartile</div>
                  <div style={{ fontSize:13, fontWeight:700, color:'#888', paddingBottom:4 }}>% Male</div>
                  <div style={{ fontSize:13, fontWeight:700, color:'#888', paddingBottom:4 }}>% Female</div>
                  {QUARTILE_ROWS.map(row => (
                    <>
                      <div key={`lbl-${row.key}`} style={{ fontSize:14, color:'var(--charcoal)', fontWeight:500 }}>{row.label}</div>
                      <input key={`m-${row.key}`} type="number" step="0.1" value={quartileMale[row.key as keyof typeof quartileMale]}
                        onChange={e => setQuartileMale(q => ({ ...q, [row.key]: e.target.value }))}
                        placeholder="e.g. 62" style={{ ...inp, marginBottom:0 }} />
                      <input key={`f-${row.key}`} type="number" step="0.1" value={quartileFemale[row.key as keyof typeof quartileFemale]}
                        onChange={e => setQuartileFemale(q => ({ ...q, [row.key]: e.target.value }))}
                        placeholder="e.g. 38" style={{ ...inp, marginBottom:0 }} />
                    </>
                  ))}
                </div>
              </div>

              <div style={card}>
                <h2 style={sectionH}>Context</h2>
                <div style={{ display:'flex', flexDirection:'column', gap:18 }}>
                  <div>
                    <label style={lbl}>What do you think is the main driver of your gap? <span style={{ color:'#c00' }}>*</span></label>
                    <p style={hint}>For example: a higher proportion of women in part-time or junior roles, underrepresentation at senior levels, a male-dominated technical workforce</p>
                    <textarea value={mainDriver} onChange={e => setMainDriver(e.target.value)} placeholder="Describe what you believe is behind your figures..." style={{ ...inp, minHeight:90, resize:'vertical' }} required />
                  </div>
                  <div>
                    <label style={lbl}>What actions are you currently taking or planning? <span style={{ color:'#c00' }}>*</span></label>
                    <p style={hint}>Even if early-stage, include anything relevant: mentoring programmes, flexible working policies, blind recruitment, pipeline reviews</p>
                    <textarea value={actions} onChange={e => setActions(e.target.value)} placeholder="List your current or planned actions..." style={{ ...inp, minHeight:90, resize:'vertical' }} required />
                  </div>
                </div>
              </div>

              {error && <div style={{ background:'#fff0f0', border:'1px solid #ffccc7', borderRadius:8, padding:'12px 16px', color:'#c0392b', fontSize:14, marginBottom:16 }}>{error}</div>}
              <button type="submit" style={{ background:'var(--charcoal)', color:'var(--white)', border:'none', borderRadius:8, padding:'14px 28px', fontSize:16, fontWeight:600, cursor:'pointer', fontFamily:'inherit' }}>
                Build my statement
              </button>
            </form>
          </>
        )}

        {loading && (
          <div style={{ display:'flex', flexDirection:'column', alignItems:'center', justifyContent:'center', minHeight:400, gap:20 }}>
            <div style={{ width:48, height:48, border:'4px solid rgba(201,168,76,0.3)', borderTop:'4px solid #C9A84C', borderRadius:'50%', animation:'spin 0.9s linear infinite' }} />
            <p style={{ fontSize:15, color:'#555', fontWeight:500 }}>{LOADING_STEPS[loadingStep]}</p>
            <style>{`@keyframes spin { to { transform: rotate(360deg); } }`}</style>
          </div>
        )}

        {result && !loading && (
          <div style={{ display:'flex', flexDirection:'column', gap:24 }}>
            <div style={{ display:'flex', alignItems:'flex-start', justifyContent:'space-between', flexWrap:'wrap', gap:12 }}>
              <div>
                <h1 style={{ fontSize:26, fontWeight:700, color:'var(--charcoal)', margin:0 }}>
                  {result.orgName ? `${result.orgName}: Gender Pay Gap Statement` : 'Your Gender Pay Gap Statement'}
                </h1>
                {result.reportingYear && <p style={{ fontSize:14, color:'#888', marginTop:4 }}>Reporting year: {result.reportingYear} · Generated by The Inclusion Edit</p>}
              </div>
              <div style={{ display:'flex', gap:10, flexWrap:'wrap' }}>
                <button onClick={() => copy(buildFullText(result), 'all')} style={{ background:'#C9A84C', color:'var(--white)', border:'none', borderRadius:8, padding:'10px 18px', fontSize:14, fontWeight:600, cursor:'pointer', fontFamily:'inherit' }}>
                  {copied === 'all' ? '✓ Copied' : 'Copy full report'}
                </button>
                <button onClick={() => { setResult(null); setError(''); }} style={{ background:'transparent', border:'1px solid var(--gray-soft)', borderRadius:8, padding:'10px 18px', fontSize:14, cursor:'pointer', fontFamily:'inherit', color:'var(--charcoal)' }}>
                  Start again
                </button>
              </div>
            </div>

            <div style={{ background:'var(--charcoal)', borderRadius:12, padding:'20px 24px', display:'flex', gap:24, flexWrap:'wrap' }}>
              <div style={{ flex:1, minWidth:160 }}>
                <p style={{ fontSize:11, fontWeight:700, color:'#C9A84C', textTransform:'uppercase', letterSpacing:'0.06em', margin:'0 0 4px 0' }}>Your mean gap</p>
                <p style={{ fontSize:26, fontWeight:700, color:'var(--white)', margin:'0 0 2px 0' }}>{result.meanPayGap}%</p>
                <p style={{ fontSize:13, color: parseFloat(result.meanPayGap) > result.benchMean ? '#e67e22' : '#7dcea0', margin:0 }}>{result.meanComparison}</p>
              </div>
              <div style={{ flex:1, minWidth:160 }}>
                <p style={{ fontSize:11, fontWeight:700, color:'#C9A84C', textTransform:'uppercase', letterSpacing:'0.06em', margin:'0 0 4px 0' }}>Your median gap</p>
                <p style={{ fontSize:26, fontWeight:700, color:'var(--white)', margin:'0 0 2px 0' }}>{result.medianPayGap}%</p>
                <p style={{ fontSize:13, color: parseFloat(result.medianPayGap) > result.benchMedian ? '#e67e22' : '#7dcea0', margin:0 }}>{result.medianComparison}</p>
              </div>
              <div style={{ flex:1, minWidth:160 }}>
                <p style={{ fontSize:11, fontWeight:700, color:'#C9A84C', textTransform:'uppercase', letterSpacing:'0.06em', margin:'0 0 4px 0' }}>Sector benchmarks</p>
                <p style={{ fontSize:15, color:'var(--white)', margin:'0 0 2px 0' }}>Mean: {result.benchMean}% · Median: {result.benchMedian}%</p>
                <p style={{ fontSize:13, color:'#aaa', margin:0 }}>{result.sector}</p>
              </div>
            </div>

            {[
              { key:'statement',     title:'Your narrative statement',           subtitle:'Ready to publish on your website or annual report', gold:false },
              { key:'sectorContext', title:'Sector context',                     subtitle:'How your figures compare to your sector', gold:false },
              { key:'actionsReview', title:'Actions review',                     subtitle:'How your current actions measure up and where to strengthen', gold:true },
              { key:'strengthenNext',title:'Strengthen next year',               subtitle:'Specific recommendations so next year\'s statement can say something different', gold:true },
              { key:'shortVersion',  title:'Short version',                      subtitle:'For a social post or internal announcement when you publish', gold:false },
            ].map(({ key, title, subtitle, gold }) => {
              const text = result[key as keyof Result] as string;
              return (
                <div key={key} style={{ background:'var(--white)', borderRadius:12, padding:'22px 26px', boxShadow:'0 1px 4px rgba(0,0,0,0.06)', borderLeft: gold ? '3px solid #C9A84C' : '3px solid var(--charcoal)' }}>
                  <div style={{ display:'flex', alignItems:'flex-start', justifyContent:'space-between', gap:12, marginBottom:12 }}>
                    <div>
                      <p style={{ fontSize:16, fontWeight:700, color:'var(--charcoal)', margin:'0 0 2px 0' }}>{title}</p>
                      <p style={{ fontSize:13, color:'#888', margin:0 }}>{subtitle}</p>
                    </div>
                    <button onClick={() => copy(text, key)} style={{ background:'transparent', border:'1px solid var(--gray-soft)', borderRadius:6, padding:'6px 12px', fontSize:13, cursor:'pointer', fontFamily:'inherit', color:'var(--charcoal)', whiteSpace:'nowrap', flexShrink:0 }}>
                      {copied === key ? '✓ Copied' : 'Copy'}
                    </button>
                  </div>
                  <p style={{ fontSize:15, color:'#333', margin:0, lineHeight:1.75, whiteSpace:'pre-wrap' }}>{text}</p>
                </div>
              );
            })}

            <div style={{ background:'rgba(201,168,76,0.1)', border:'1px solid #C9A84C', borderRadius:12, padding:'22px 26px', display:'flex', alignItems:'center', justifyContent:'space-between', flexWrap:'wrap', gap:16 }}>
              <div>
                <p style={{ fontSize:15, fontWeight:700, color:'var(--charcoal)', margin:'0 0 4px 0' }}>Ready to share</p>
                <p style={{ fontSize:13, color:'#777', margin:0 }}>Copy the full report to share with your communications team, senior leadership, or board.</p>
              </div>
              <button onClick={() => copy(buildFullText(result), 'all')} style={{ background:'#C9A84C', color:'var(--white)', border:'none', borderRadius:8, padding:'12px 22px', fontSize:14, fontWeight:600, cursor:'pointer', fontFamily:'inherit', whiteSpace:'nowrap' }}>
                {copied === 'all' ? '✓ Copied' : 'Copy full report'}
              </button>
            </div>
          </div>
        )}

        {!result && !loading && (
          <div style={{ marginTop:64, borderTop:'1px solid var(--gray-soft)', paddingTop:48 }}>
            <p style={{ fontSize:11, fontWeight:700, color:'#C9A84C', textTransform:'uppercase', letterSpacing:'0.08em', margin:'0 0 10px 0' }}>About this topic</p>
            <h2 style={{ fontSize:22, fontWeight:700, color:'var(--charcoal)', margin:'0 0 20px 0' }}>Why the narrative matters more than the numbers</h2>
            <p style={{ fontSize:15, color:'#444', lineHeight:1.75, maxWidth:700, margin:'0 0 16px 0' }}>
              Most organisations treat gender pay gap reporting as a compliance exercise. Submit the figures, meet the deadline, move on. The result is thousands of reports on a public database that say very little about what is actually happening inside those organisations; or what anyone intends to do about it.
            </p>
            <p style={{ fontSize:15, color:'#444', lineHeight:1.75, maxWidth:700, margin:'0 0 16px 0' }}>
              A well-written narrative does three things the numbers cannot. It explains the context behind the gap, so readers understand whether it reflects occupational segregation, part-time working patterns, pipeline gaps, or something else entirely. It demonstrates accountability, showing employees, candidates, and stakeholders that leadership has actually looked at the data. And it sets a public commitment: when you name what you are going to do, you create a basis for being held to it the following year.
            </p>
            <p style={{ fontSize:15, color:'#444', lineHeight:1.75, maxWidth:700, margin:'0 0 32px 0' }}>
              Organisations that publish a thoughtful narrative alongside their figures consistently report stronger employee trust and better candidate perception than those that publish numbers alone.
            </p>
            <h3 style={{ fontSize:17, fontWeight:700, color:'var(--charcoal)', margin:'0 0 12px 0' }}>What you are required to publish</h3>
            <p style={{ fontSize:15, color:'#444', lineHeight:1.75, maxWidth:700, margin:'0 0 32px 0' }}>
              The six statutory figures are: mean and median gender pay gap in hourly pay; mean and median bonus gap; the proportion of men and women receiving a bonus; and the proportion of men and women in each pay quartile. These go to the government&apos;s reporting service by 4 April each year. A written statement is not a legal requirement; but the Equality and Human Rights Commission recommends one, and most employers who take inclusion seriously include it.
            </p>
            <h3 style={{ fontSize:17, fontWeight:700, color:'var(--charcoal)', margin:'0 0 12px 0' }}>Where to publish your narrative</h3>
            <p style={{ fontSize:15, color:'#444', lineHeight:1.75, maxWidth:700, margin:0 }}>
              Most organisations publish it on their website alongside or shortly after their statutory submission, often on a dedicated pay gap or inclusion page. Some include it in their annual report or ESG report. If you have an employee intranet, sharing it internally before it goes public builds trust with your workforce.
            </p>
          </div>
        )}
      </main>
      <BottomBanner />
    </div>
  );
}
