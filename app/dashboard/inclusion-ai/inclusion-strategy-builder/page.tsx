'use client';
import { useState } from 'react';
import PlatformNav from '@/app/components/PlatformNav';
import BottomBanner from '@/app/components/BottomBanner';

const SECTORS = [
  'Financial services','Legal','Technology','Healthcare / NHS',
  'Education (higher education)','Education (schools)','Public sector',
  'Third sector / charity','Hospitality and retail','Professional services','Other',
];

const ORG_SIZES = [
  'Under 50 employees','50 to 249 employees','250 to 999 employees',
  '1,000 to 4,999 employees','5,000+ employees',
];

const EDI_LEADS = [
  { value: 'hr', label: 'HR team' },
  { value: 'leadership', label: 'Senior leadership' },
  { value: 'inclusion_lead', label: 'Dedicated inclusion lead' },
  { value: 'manager', label: 'Manager or champion network' },
  { value: 'none', label: 'No one currently owns it' },
];

const PRESSURE_POINTS = [
  'Recruitment diversity','Pay gap reporting','Retention and progression',
  'Culture and belonging','Leadership representation','Policy gaps',
  'Neurodiversity and disability','Supplier diversity','Employee wellbeing',
  'Data and measurement','Psychological safety','Menopause and gender inclusion',
];

const TIMELINES = [
  { value: 'scratch', label: 'Starting from scratch' },
  { value: 'refresh', label: 'Refreshing an existing strategy' },
  { value: 'deadline', label: 'Preparing for a specific deadline' },
];

const LOADING_STEPS = [
  'Reviewing your organisation profile...',
  'Mapping your pressure points to evidence...',
  'Prioritising your focus areas...',
  'Building objectives and metrics...',
  'Drafting your board summary...',
  'Finalising your strategy framework...',
];

type Result = {
  orgName: string;
  sector: string;
  focusAreas: string;
  objectivesMetrics: string;
  quickWins: string;
  longTermShifts: string;
  boardSummary: string;
  stopDoing: string;
};

export default function InclusionStrategyBuilder() {
  const [orgName, setOrgName] = useState('');
  const [sector, setSector] = useState('');
  const [orgSize, setOrgSize] = useState('');
  const [ediLead, setEdiLead] = useState('');
  const [currentState, setCurrentState] = useState('');
  const [pressurePoints, setPressurePoints] = useState<string[]>([]);
  const [pressurePointsOther, setPressurePointsOther] = useState('');
  const [leadershipCommitment, setLeadershipCommitment] = useState('');
  const [timeline, setTimeline] = useState('');
  const [stopDoing, setStopDoing] = useState('');
  const [loading, setLoading] = useState(false);
  const [loadingStep, setLoadingStep] = useState(0);
  const [result, setResult] = useState<Result | null>(null);
  const [error, setError] = useState('');
  const [copied, setCopied] = useState<string | null>(null);

  function togglePressure(p: string) {
    setPressurePoints(prev =>
      prev.includes(p) ? prev.filter(x => x !== p) : prev.length < 3 ? [...prev, p] : prev
    );
  }

  function copy(text: string, key: string) {
    navigator.clipboard.writeText(text);
    setCopied(key);
    setTimeout(() => setCopied(null), 2000);
  }

  function buildFullText(): string {
    if (!result) return '';
    const lines: string[] = [];
    lines.push(`INCLUSION STRATEGY FRAMEWORK`);
    if (result.orgName) lines.push(result.orgName);
    lines.push(`Sector: ${result.sector}`);
    lines.push('');
    lines.push('FOCUS AREAS');
    lines.push(result.focusAreas);
    lines.push('');
    lines.push('OBJECTIVES AND METRICS');
    lines.push(result.objectivesMetrics);
    lines.push('');
    lines.push('QUICK WINS (First 90 days)');
    lines.push(result.quickWins);
    lines.push('');
    lines.push('LONG-TERM SHIFTS');
    lines.push(result.longTermShifts);
    lines.push('');
    lines.push('BOARD SUMMARY');
    lines.push(result.boardSummary);
    lines.push('');
    lines.push('ONE THING TO STOP');
    lines.push(result.stopDoing);
    lines.push('');
    lines.push('Generated by The Inclusion Edit Inclusion Strategy Builder');
    return lines.join('\n');
  }

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    if (!sector || !orgSize || !ediLead || !timeline || pressurePoints.length === 0) {
      setError('Please complete all required fields and select at least one pressure point.');
      return;
    }
    setError('');
    setLoading(true);
    setResult(null);
    setLoadingStep(0);
    const interval = setInterval(() => {
      setLoadingStep(s => (s + 1) % LOADING_STEPS.length);
    }, 1800);
    try {
      const res = await fetch('/api/inclusion-strategy-builder', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          orgName, sector, orgSize, ediLead, currentState,
          pressurePoints, pressurePointsOther, leadershipCommitment,
          timeline, stopDoing,
        }),
      });
      const data = await res.json();
      if (data.error) { setError(data.error); }
      else { setResult(data); }
    } catch {
      setError('Something went wrong. Please try again.');
    } finally {
      clearInterval(interval);
      setLoading(false);
    }
  }

  const btnBase: React.CSSProperties = {
    border: '1.5px solid #C9A84C', borderRadius: 8, background: 'transparent',
    color: 'var(--charcoal)', padding: '8px 18px', cursor: 'pointer',
    fontSize: 14, fontWeight: 500, transition: 'all 0.15s',
  };
  const btnActive: React.CSSProperties = {
    ...btnBase, background: 'rgba(201,168,76,0.35)', borderColor: '#C9A84C',
  };
  const inputStyle: React.CSSProperties = {
    width: '100%', padding: '10px 14px', borderRadius: 8,
    border: '1.5px solid var(--gray-soft)', fontSize: 15,
    background: 'var(--white)', color: 'var(--charcoal)',
    fontFamily: 'inherit', boxSizing: 'border-box',
  };
  const textareaStyle: React.CSSProperties = {
    ...inputStyle, minHeight: 90, resize: 'vertical',
  };
  const labelStyle: React.CSSProperties = {
    display: 'block', fontWeight: 600, marginBottom: 8,
    fontSize: 15, color: 'var(--charcoal)',
  };
  const sectionCard: React.CSSProperties = {
    background: 'var(--white)', borderRadius: 12, padding: '28px 32px',
    marginBottom: 24, border: '1px solid var(--gray-soft)',
  };
  const resultCard: React.CSSProperties = {
    background: 'var(--white)', borderRadius: 12, padding: '24px 28px',
    marginBottom: 20, border: '1px solid var(--gray-soft)',
  };

  return (
    <div style={{ minHeight: '100vh', background: 'var(--sage-xlight)', fontFamily: 'inherit' }}>
      <PlatformNav />
      <div style={{ maxWidth: 800, margin: '0 auto', padding: '48px 24px 80px' }}>

        <div style={{ marginBottom: 36 }}>
          <div style={{ display: 'inline-block', background: 'rgba(201,168,76,0.2)', border: '1px solid #C9A84C', borderRadius: 20, padding: '4px 14px', fontSize: 12, fontWeight: 700, letterSpacing: 1, color: '#8a6d1f', marginBottom: 14 }}>
            INCLUSION AI
          </div>
          <h1 style={{ fontSize: 32, fontWeight: 800, color: 'var(--charcoal)', margin: '0 0 12px' }}>
            Inclusion Strategy Builder
          </h1>
          <p style={{ fontSize: 16, color: '#555', lineHeight: 1.6, maxWidth: 620, margin: 0 }}>
            Tell us about your organisation and where you are on your inclusion journey. We will generate a 12-month strategy framework: prioritised focus areas, measurable objectives, quick wins, and a board-ready summary.
          </p>
        </div>

        {!result && (
          <form onSubmit={handleSubmit}>
            {/* Section 1: About your organisation */}
            <div style={sectionCard}>
              <h2 style={{ fontSize: 18, fontWeight: 700, color: 'var(--charcoal)', margin: '0 0 20px' }}>About your organisation</h2>

              <div style={{ marginBottom: 20 }}>
                <label style={labelStyle}>Organisation name <span style={{ fontWeight: 400, color: '#888' }}>(optional)</span></label>
                <input style={inputStyle} value={orgName} onChange={e => setOrgName(e.target.value)} placeholder="e.g. Acme Ltd" />
              </div>

              <div style={{ marginBottom: 20 }}>
                <label style={labelStyle}>Sector <span style={{ color: '#c0392b' }}>*</span></label>
                <div style={{ display: 'flex', flexWrap: 'wrap', gap: 10 }}>
                  {SECTORS.map(s => (
                    <button key={s} type="button" style={sector === s ? btnActive : btnBase} onClick={() => setSector(s)}>{s}</button>
                  ))}
                </div>
              </div>

              <div style={{ marginBottom: 20 }}>
                <label style={labelStyle}>Organisation size <span style={{ color: '#c0392b' }}>*</span></label>
                <div style={{ display: 'flex', flexWrap: 'wrap', gap: 10 }}>
                  {ORG_SIZES.map(s => (
                    <button key={s} type="button" style={orgSize === s ? btnActive : btnBase} onClick={() => setOrgSize(s)}>{s}</button>
                  ))}
                </div>
              </div>

              <div>
                <label style={labelStyle}>Who currently leads on EDI? <span style={{ color: '#c0392b' }}>*</span></label>
                <div style={{ display: 'flex', flexWrap: 'wrap', gap: 10 }}>
                  {EDI_LEADS.map(l => (
                    <button key={l.value} type="button" style={ediLead === l.value ? btnActive : btnBase} onClick={() => setEdiLead(l.value)}>{l.label}</button>
                  ))}
                </div>
              </div>
            </div>

            {/* Section 2: Where you are now */}
            <div style={sectionCard}>
              <h2 style={{ fontSize: 18, fontWeight: 700, color: 'var(--charcoal)', margin: '0 0 20px' }}>Where you are now</h2>

              <div style={{ marginBottom: 20 }}>
                <label style={labelStyle}>What is already in place? <span style={{ fontWeight: 400, color: '#888' }}>(optional)</span></label>
                <p style={{ fontSize: 13, color: '#888', margin: '0 0 8px' }}>Policies, previous strategies, training programmes, staff networks, data collection. Even if it feels limited, tell us what exists.</p>
                <textarea style={textareaStyle} value={currentState} onChange={e => setCurrentState(e.target.value)} placeholder="e.g. We have an equal opportunities policy and ran unconscious bias training last year. We collect basic diversity data at recruitment but do not analyse it further." />
              </div>

              <div style={{ marginBottom: 20 }}>
                <label style={labelStyle}>What has leadership committed to? <span style={{ fontWeight: 400, color: '#888' }}>(optional)</span></label>
                <p style={{ fontSize: 13, color: '#888', margin: '0 0 8px' }}>Any public statements, targets, or internal promises from senior leaders.</p>
                <textarea style={textareaStyle} value={leadershipCommitment} onChange={e => setLeadershipCommitment(e.target.value)} placeholder="e.g. Our CEO signed the Race at Work Charter. We have committed to publishing our ethnicity pay gap by 2026." />
              </div>

              <div>
                <label style={labelStyle}>Your timeline <span style={{ color: '#c0392b' }}>*</span></label>
                <div style={{ display: 'flex', flexWrap: 'wrap', gap: 10 }}>
                  {TIMELINES.map(t => (
                    <button key={t.value} type="button" style={timeline === t.value ? btnActive : btnBase} onClick={() => setTimeline(t.value)}>{t.label}</button>
                  ))}
                </div>
              </div>
            </div>

            {/* Section 3: Priorities */}
            <div style={sectionCard}>
              <h2 style={{ fontSize: 18, fontWeight: 700, color: 'var(--charcoal)', margin: '0 0 6px' }}>Your biggest pressure points</h2>
              <p style={{ fontSize: 13, color: '#888', margin: '0 0 16px' }}>Select up to 3. These become the foundation of your strategy.</p>
              <div style={{ display: 'flex', flexWrap: 'wrap', gap: 10, marginBottom: 16 }}>
                {PRESSURE_POINTS.map(p => (
                  <button key={p} type="button"
                    style={pressurePoints.includes(p) ? btnActive : { ...btnBase, opacity: pressurePoints.length >= 3 && !pressurePoints.includes(p) ? 0.45 : 1 }}
                    onClick={() => togglePressure(p)}>{p}</button>
                ))}
              </div>
              <div>
                <label style={{ ...labelStyle, fontWeight: 500 }}>Other <span style={{ fontWeight: 400, color: '#888' }}>(optional)</span></label>
                <input style={inputStyle} value={pressurePointsOther} onChange={e => setPressurePointsOther(e.target.value)} placeholder="Describe another pressure point not listed above" />
              </div>
            </div>

            {/* Section 4: One thing to stop */}
            <div style={sectionCard}>
              <h2 style={{ fontSize: 18, fontWeight: 700, color: 'var(--charcoal)', margin: '0 0 6px' }}>One thing you want to stop doing <span style={{ fontWeight: 400, fontSize: 15, color: '#888' }}>(optional)</span></h2>
              <p style={{ fontSize: 13, color: '#888', margin: '0 0 12px' }}>Is there an approach you have tried that has not worked, or a habit you want to move away from?</p>
              <textarea style={textareaStyle} value={stopDoing} onChange={e => setStopDoing(e.target.value)} placeholder="e.g. Running one-off training days that do not connect to any wider plan." />
            </div>

            {error && <p style={{ color: '#c0392b', marginBottom: 16, fontWeight: 500 }}>{error}</p>}

            <button type="submit" disabled={loading}
              style={{ background: 'var(--charcoal)', color: 'var(--white)', border: 'none', borderRadius: 10, padding: '14px 36px', fontSize: 16, fontWeight: 700, cursor: loading ? 'not-allowed' : 'pointer', opacity: loading ? 0.7 : 1 }}>
              Build my strategy framework
            </button>
          </form>
        )}

        {loading && (
          <div style={{ textAlign: 'center', padding: '80px 0' }}>
            <div style={{ width: 48, height: 48, border: '4px solid var(--gray-soft)', borderTop: '4px solid #C9A84C', borderRadius: '50%', margin: '0 auto 24px', animation: 'spin 0.9s linear infinite' }} />
            <style>{`@keyframes spin { to { transform: rotate(360deg); } }`}</style>
            <p style={{ fontSize: 17, color: 'var(--charcoal)', fontWeight: 600 }}>{LOADING_STEPS[loadingStep]}</p>
            <p style={{ fontSize: 14, color: '#888', marginTop: 8 }}>This takes around 30 seconds</p>
          </div>
        )}

        {result && (
          <div>
            {/* Header banner */}
            <div style={{ background: 'var(--charcoal)', borderRadius: 14, padding: '28px 32px', marginBottom: 28, color: 'var(--white)' }}>
              <div style={{ fontSize: 12, fontWeight: 700, letterSpacing: 1, opacity: 0.6, marginBottom: 8 }}>INCLUSION STRATEGY FRAMEWORK</div>
              <h2 style={{ fontSize: 24, fontWeight: 800, margin: '0 0 6px' }}>{result.orgName || 'Your Organisation'}</h2>
              <p style={{ margin: 0, opacity: 0.75, fontSize: 15 }}>{result.sector} · 12-month framework</p>
            </div>

            {/* Focus areas */}
            <div style={resultCard}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: 14 }}>
                <h3 style={{ fontSize: 17, fontWeight: 700, color: 'var(--charcoal)', margin: 0 }}>Three Priority Focus Areas</h3>
                <button onClick={() => copy(result.focusAreas, 'focus')} style={{ ...btnBase, fontSize: 13, padding: '6px 14px' }}>{copied === 'focus' ? 'Copied' : 'Copy'}</button>
              </div>
              <p style={{ whiteSpace: 'pre-wrap', lineHeight: 1.7, color: '#333', margin: 0, fontSize: 15 }}>{result.focusAreas}</p>
            </div>

            {/* Objectives and metrics */}
            <div style={resultCard}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: 14 }}>
                <h3 style={{ fontSize: 17, fontWeight: 700, color: 'var(--charcoal)', margin: 0 }}>Objectives and Metrics</h3>
                <button onClick={() => copy(result.objectivesMetrics, 'objectives')} style={{ ...btnBase, fontSize: 13, padding: '6px 14px' }}>{copied === 'objectives' ? 'Copied' : 'Copy'}</button>
              </div>
              <p style={{ whiteSpace: 'pre-wrap', lineHeight: 1.7, color: '#333', margin: 0, fontSize: 15 }}>{result.objectivesMetrics}</p>
            </div>

            {/* Quick wins */}
            <div style={{ ...resultCard, borderLeft: '4px solid #C9A84C' }}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: 14 }}>
                <h3 style={{ fontSize: 17, fontWeight: 700, color: 'var(--charcoal)', margin: 0 }}>Quick Wins: First 90 Days</h3>
                <button onClick={() => copy(result.quickWins, 'quick')} style={{ ...btnBase, fontSize: 13, padding: '6px 14px' }}>{copied === 'quick' ? 'Copied' : 'Copy'}</button>
              </div>
              <p style={{ whiteSpace: 'pre-wrap', lineHeight: 1.7, color: '#333', margin: 0, fontSize: 15 }}>{result.quickWins}</p>
            </div>

            {/* Long-term shifts */}
            <div style={resultCard}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: 14 }}>
                <h3 style={{ fontSize: 17, fontWeight: 700, color: 'var(--charcoal)', margin: 0 }}>Long-Term Structural Shifts</h3>
                <button onClick={() => copy(result.longTermShifts, 'longterm')} style={{ ...btnBase, fontSize: 13, padding: '6px 14px' }}>{copied === 'longterm' ? 'Copied' : 'Copy'}</button>
              </div>
              <p style={{ whiteSpace: 'pre-wrap', lineHeight: 1.7, color: '#333', margin: 0, fontSize: 15 }}>{result.longTermShifts}</p>
            </div>

            {/* Board summary */}
            <div style={{ ...resultCard, background: '#1c2b2b', borderColor: '#1c2b2b' }}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: 14 }}>
                <h3 style={{ fontSize: 17, fontWeight: 700, color: 'var(--white)', margin: 0 }}>Board Summary</h3>
                <button onClick={() => copy(result.boardSummary, 'board')} style={{ ...btnBase, fontSize: 13, padding: '6px 14px', borderColor: 'rgba(201,168,76,0.6)', color: 'var(--white)' }}>{copied === 'board' ? 'Copied' : 'Copy'}</button>
              </div>
              <p style={{ whiteSpace: 'pre-wrap', lineHeight: 1.8, color: 'rgba(255,255,255,0.85)', margin: 0, fontSize: 15, fontStyle: 'italic' }}>{result.boardSummary}</p>
            </div>

            {/* Stop doing */}
            <div style={{ ...resultCard, background: 'rgba(201,168,76,0.12)', borderColor: '#C9A84C' }}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: 14 }}>
                <h3 style={{ fontSize: 17, fontWeight: 700, color: 'var(--charcoal)', margin: 0 }}>One Thing to Stop</h3>
                <button onClick={() => copy(result.stopDoing, 'stop')} style={{ ...btnBase, fontSize: 13, padding: '6px 14px' }}>{copied === 'stop' ? 'Copied' : 'Copy'}</button>
              </div>
              <p style={{ whiteSpace: 'pre-wrap', lineHeight: 1.7, color: '#333', margin: 0, fontSize: 15 }}>{result.stopDoing}</p>
            </div>

            {/* Consultant handoff */}
            <div style={{ background: 'var(--white)', borderRadius: 12, padding: '24px 28px', marginBottom: 20, border: '1px solid var(--gray-soft)', textAlign: 'center' }}>
              <p style={{ fontSize: 15, color: '#555', lineHeight: 1.7, margin: '0 0 16px' }}>
                This framework gives you a clear starting point. To turn it into a delivery plan your organisation will actually implement; including stakeholder buy-in, bespoke data analysis, and ongoing implementation support; talk to The Inclusion Edit.
              </p>
              <a href="/dashboard/apply" style={{ display: 'inline-block', background: 'var(--charcoal)', color: 'var(--white)', padding: '12px 28px', borderRadius: 8, fontWeight: 700, fontSize: 15, textDecoration: 'none' }}>
                Work with us
              </a>
            </div>

            {/* Copy all and reset */}
            <div style={{ display: 'flex', gap: 14, flexWrap: 'wrap', marginTop: 8 }}>
              <button onClick={() => copy(buildFullText(), 'all')} style={{ ...btnBase, padding: '12px 24px', fontSize: 15 }}>{copied === 'all' ? 'Copied' : 'Copy full framework'}</button>
              <button onClick={() => { setResult(null); setOrgName(''); setSector(''); setOrgSize(''); setEdiLead(''); setCurrentState(''); setPressurePoints([]); setPressurePointsOther(''); setLeadershipCommitment(''); setTimeline(''); setStopDoing(''); }} style={{ background: 'transparent', border: '1.5px solid var(--gray-soft)', borderRadius: 8, padding: '12px 24px', fontSize: 15, cursor: 'pointer', color: '#666' }}>
                Start again
              </button>
            </div>

            {/* About this topic */}
            <div style={{ background: 'var(--white)', borderRadius: 12, padding: '28px 32px', marginTop: 32, border: '1px solid var(--gray-soft)' }}>
              <h3 style={{ fontSize: 16, fontWeight: 700, color: 'var(--charcoal)', margin: '0 0 12px' }}>About this tool</h3>
              <p style={{ fontSize: 14, color: '#555', lineHeight: 1.7, margin: 0 }}>
                The Inclusion Strategy Builder generates a tailored framework based on your organisation's context, sector, and stated priorities. It draws on established EDI best practice and evidence to surface what matters most for organisations like yours. It is designed as a starting point: a structured way to think through priorities, set meaningful objectives, and communicate clearly with leadership. It does not replace the judgement, stakeholder engagement, and implementation support that a consultant brings; but it gives you a far stronger foundation than starting from a blank page.
              </p>
            </div>
          </div>
        )}

        {!result && !loading && (
          <div style={{ background: 'var(--white)', borderRadius: 12, padding: '28px 32px', marginTop: 32, border: '1px solid var(--gray-soft)' }}>
            <h3 style={{ fontSize: 16, fontWeight: 700, color: 'var(--charcoal)', margin: '0 0 12px' }}>About this tool</h3>
            <p style={{ fontSize: 14, color: '#555', lineHeight: 1.7, margin: 0 }}>
              The Inclusion Strategy Builder generates a tailored framework based on your organisation's context, sector, and stated priorities. It draws on established EDI best practice and evidence to surface what matters most for organisations like yours. It is designed as a starting point: a structured way to think through priorities, set meaningful objectives, and communicate clearly with leadership. It does not replace the judgement, stakeholder engagement, and implementation support that a consultant brings; but it gives you a far stronger foundation than starting from a blank page.
            </p>
          </div>
        )}

      </div>
      <BottomBanner />
    </div>
  );
}
